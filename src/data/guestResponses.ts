import type { ScenarioId } from '../types';

export type BaseReplyBucket =
  | 'excuse_or_rude'
  | 'policy_violation'
  | 'apology_only'
  | 'vague_reply'
  | 'resolved_final'
  | 'escalated_final';

export interface TopicReplyBranch {
  id: string;
  label: string;
  /** Keywords proving the trainee explicitly proposed this topic. */
  keywords: string[];
  /**
   * When true (default), a keyword match immediately followed by refusal wording
   * (e.g. "객실 변경은 어렵습니다") is NOT credited as offering this solution.
   * Set false for policy-boundary explanation topics where explaining a restriction IS the SOP.
   */
  requirePositive?: boolean;
  /** Varied natural guest replies that ONLY react to THIS exact topic. */
  replies: string[];
}

export interface ComboReplyBranch {
  /** Every listed topic ID must be matched in the trainee's CURRENT message. */
  requiredTopicIds: string[];
  replies: string[];
}

export interface ScenarioResponseBank {
  topics: TopicReplyBranch[];
  comboReplies?: ComboReplyBranch[];
  /** If set, missing this topic reduces SOP/resolution scores and shows missingSafety coaching. */
  requiredSafetyTopicId?: string;
  /** Patterns matching forbidden policy violations (checked with refusal-safety guard). */
  forbiddenConcessionPatterns?: RegExp[];
  baseReplies: Record<BaseReplyBucket, string[]>;
  coaching: {
    excuseOrRude: string;
    policyViolation: string;
    apologyOnly: string;
    vagueReply: string;
    missingSafety?: string;
  };
}

