export function isValidScenarioId(id: string | null | undefined): id is ScenarioId {
  if (!id) return false;
  return SCENARIOS.some((s) => s.id === id);
}

export function getScenarioById(id: ScenarioId): ScenarioDefinition {
  const found = SCENARIOS.find((s) => s.id === id);
  return found ?? SCENARIOS[0];
}
